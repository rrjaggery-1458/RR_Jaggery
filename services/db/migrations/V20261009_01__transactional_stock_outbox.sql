BEGIN;

DO $$
BEGIN
    IF to_regnamespace('commerce_schema') IS NULL THEN
        RAISE EXCEPTION 'Required schema commerce_schema does not exist; aborting stock outbox migration';
    END IF;
    IF to_regnamespace('customer_schema') IS NULL THEN
        RAISE EXCEPTION 'Required schema customer_schema does not exist; aborting stock outbox migration';
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS commerce_schema.stock_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_key VARCHAR(255) NOT NULL,
    depends_on_command_key VARCHAR(255),
    operation VARCHAR(20) NOT NULL,
    sku VARCHAR(100) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL,
    reference_id VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_error VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS customer_schema.stock_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_key VARCHAR(255) NOT NULL,
    depends_on_command_key VARCHAR(255),
    operation VARCHAR(20) NOT NULL,
    sku VARCHAR(100) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL,
    reference_id VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_error VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at TIMESTAMPTZ
);

DO $$
DECLARE
    target RECORD;
    expected RECORD;
    actual_type TEXT;
    actual_length INTEGER;
    actual_precision INTEGER;
    actual_scale INTEGER;
    actual_identity TEXT;
    existing_definition TEXT;
    constraint_name TEXT;
    constraint_expression TEXT;
BEGIN
    FOR target IN
        SELECT * FROM (VALUES
            ('commerce_schema', 'stock_outbox'),
            ('customer_schema', 'stock_outbox')
        ) AS tables_to_check(schema_name, table_name)
    LOOP
        FOR expected IN
            SELECT * FROM (VALUES
                ('id', 'bigint', NULL::INTEGER, NULL::INTEGER, NULL::INTEGER, 'NO', 'YES'),
                ('command_key', 'character varying', 255, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('depends_on_command_key', 'character varying', 255, NULL::INTEGER, NULL::INTEGER, 'YES', 'NO'),
                ('operation', 'character varying', 20, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('sku', 'character varying', 100, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('quantity', 'numeric', NULL::INTEGER, 14, 3, 'NO', 'NO'),
                ('reference_id', 'character varying', 255, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('status', 'character varying', 20, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('attempts', 'integer', NULL::INTEGER, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('next_attempt_at', 'timestamp with time zone', NULL::INTEGER, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('last_error', 'character varying', 500, NULL::INTEGER, NULL::INTEGER, 'YES', 'NO'),
                ('created_at', 'timestamp with time zone', NULL::INTEGER, NULL::INTEGER, NULL::INTEGER, 'NO', 'NO'),
                ('processed_at', 'timestamp with time zone', NULL::INTEGER, NULL::INTEGER, NULL::INTEGER, 'YES', 'NO')
            ) AS required_columns(column_name, data_type, max_length, numeric_precision, numeric_scale, is_nullable, is_identity)
        LOOP
            SELECT c.data_type, c.character_maximum_length, c.numeric_precision, c.numeric_scale, c.is_identity
            INTO actual_type, actual_length, actual_precision, actual_scale, actual_identity
            FROM information_schema.columns c
            WHERE c.table_schema = target.schema_name
              AND c.table_name = target.table_name
              AND c.column_name = expected.column_name;

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Existing %.% is missing required column %; no table was replaced',
                    target.schema_name, target.table_name, expected.column_name;
            END IF;
            IF actual_type <> expected.data_type
                OR (expected.max_length IS NOT NULL AND actual_length <> expected.max_length)
                OR (expected.numeric_precision IS NOT NULL AND actual_precision <> expected.numeric_precision)
                OR (expected.numeric_scale IS NOT NULL AND actual_scale <> expected.numeric_scale)
                OR (SELECT c.is_nullable FROM information_schema.columns c
                    WHERE c.table_schema = target.schema_name
                      AND c.table_name = target.table_name
                      AND c.column_name = expected.column_name) <> expected.is_nullable
                OR actual_identity <> expected.is_identity THEN
                RAISE EXCEPTION 'Existing %.%.% has incompatible type/size (%, %, %, %); expected (%, %, %, %)',
                    target.schema_name, target.table_name, expected.column_name,
                    actual_type, actual_length, actual_precision, actual_scale,
                    expected.data_type, expected.max_length, expected.numeric_precision, expected.numeric_scale;
            END IF;
        END LOOP;

        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN status SET DEFAULT %L',
            target.schema_name, target.table_name, 'PENDING');
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN attempts SET DEFAULT 0',
            target.schema_name, target.table_name);
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN next_attempt_at SET DEFAULT NOW()',
            target.schema_name, target.table_name);
        EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN created_at SET DEFAULT NOW()',
            target.schema_name, target.table_name);

        FOR constraint_name, constraint_expression IN
            SELECT * FROM (VALUES
                ('ck_stock_outbox_operation', 'operation IN (''DEDUCT'', ''RESTORE'')'),
                ('ck_stock_outbox_quantity', 'quantity > 0'),
                ('ck_stock_outbox_status', 'status IN (''PENDING'', ''SUCCEEDED'', ''FAILED'')'),
                ('ck_stock_outbox_attempts', 'attempts >= 0')
            ) AS required_checks(name, expression)
        LOOP
            SELECT pg_get_constraintdef(c.oid, true)
            INTO existing_definition
            FROM pg_constraint c
            WHERE c.conrelid = format('%I.%I', target.schema_name, target.table_name)::regclass
              AND c.conname = constraint_name;

            IF FOUND THEN
                IF constraint_name = 'ck_stock_outbox_operation'
                    AND NOT (
                        existing_definition ILIKE '%operation%'
                        AND existing_definition ILIKE '%= ANY%'
                        AND existing_definition ILIKE '%DEDUCT%'
                        AND existing_definition ILIKE '%RESTORE%'
                        AND existing_definition NOT ILIKE '% OR %'
                        AND existing_definition NOT ILIKE '% AND %'
                        AND existing_definition NOT ILIKE '%NOT %'
                        AND existing_definition NOT ILIKE '%<>%'
                    ) THEN
                    RAISE EXCEPTION 'Constraint %.% on %.% has an unexpected definition: %',
                        constraint_name, target.table_name, target.schema_name, target.table_name, existing_definition;
                END IF;
                IF constraint_name = 'ck_stock_outbox_status'
                    AND NOT (
                        existing_definition ILIKE '%status%'
                        AND existing_definition ILIKE '%= ANY%'
                        AND existing_definition ILIKE '%PENDING%'
                        AND existing_definition ILIKE '%SUCCEEDED%'
                        AND existing_definition ILIKE '%FAILED%'
                        AND existing_definition NOT ILIKE '% OR %'
                        AND existing_definition NOT ILIKE '% AND %'
                        AND existing_definition NOT ILIKE '%NOT %'
                        AND existing_definition NOT ILIKE '%<>%'
                    ) THEN
                    RAISE EXCEPTION 'Constraint %.% on %.% has an unexpected definition: %',
                        constraint_name, target.table_name, target.schema_name, target.table_name, existing_definition;
                END IF;
                IF constraint_name = 'ck_stock_outbox_quantity'
                    AND NOT (
                        existing_definition ILIKE '%quantity%'
                        AND existing_definition ILIKE '%>%'
                        AND existing_definition ILIKE '%0%'
                        AND existing_definition NOT ILIKE '%<%'
                        AND existing_definition NOT ILIKE '% OR %'
                        AND existing_definition NOT ILIKE '% AND %'
                        AND existing_definition NOT ILIKE '%NOT %'
                    ) THEN
                    RAISE EXCEPTION 'Constraint %.% on %.% has an unexpected definition: %',
                        constraint_name, target.table_name, target.schema_name, target.table_name, existing_definition;
                END IF;
                IF constraint_name = 'ck_stock_outbox_attempts'
                    AND NOT (
                        existing_definition ILIKE '%attempts%'
                        AND existing_definition ILIKE '%>=%'
                        AND existing_definition ILIKE '%0%'
                        AND existing_definition NOT ILIKE '% OR %'
                        AND existing_definition NOT ILIKE '% AND %'
                        AND existing_definition NOT ILIKE '%NOT %'
                    ) THEN
                    RAISE EXCEPTION 'Constraint %.% on %.% has an unexpected definition: %',
                        constraint_name, target.table_name, target.schema_name, target.table_name, existing_definition;
                END IF;
                IF NOT (SELECT c.convalidated FROM pg_constraint c
                        WHERE c.conrelid = format('%I.%I', target.schema_name, target.table_name)::regclass
                          AND c.conname = constraint_name) THEN
                    EXECUTE format('ALTER TABLE %I.%I VALIDATE CONSTRAINT %I',
                        target.schema_name, target.table_name, constraint_name);
                END IF;
            ELSE
                EXECUTE format('ALTER TABLE %I.%I ADD CONSTRAINT %I CHECK (%s)',
                    target.schema_name, target.table_name, constraint_name, constraint_expression);
            END IF;
        END LOOP;

        IF NOT EXISTS (
            SELECT 1
            FROM pg_constraint c
            WHERE c.conrelid = format('%I.%I', target.schema_name, target.table_name)::regclass
              AND c.contype = 'p'
              AND pg_get_constraintdef(c.oid, true) ILIKE '%PRIMARY KEY (id)%'
        ) THEN
            RAISE EXCEPTION 'Existing %.% has no primary key on id; migration stopped without changing its data',
                target.schema_name, target.table_name;
        END IF;

        IF NOT EXISTS (
            SELECT 1
            FROM pg_index i
            JOIN pg_class table_class ON table_class.oid = i.indrelid
            JOIN pg_namespace ns ON ns.oid = table_class.relnamespace
            JOIN pg_attribute a ON a.attrelid = table_class.oid AND a.attname = 'command_key'
            WHERE ns.nspname = target.schema_name
              AND table_class.relname = target.table_name
              AND i.indisunique
              AND i.indpred IS NULL
              AND i.indnkeyatts = 1
              AND i.indkey[0] = a.attnum
        ) THEN
            EXECUTE format('ALTER TABLE %I.%I ADD CONSTRAINT %I UNIQUE (command_key)',
                target.schema_name, target.table_name,
                CASE target.schema_name
                    WHEN 'commerce_schema' THEN 'uk_commerce_stock_outbox_command'
                    ELSE 'uk_customer_stock_outbox_command'
                END);
        END IF;
    END LOOP;
END
$$;

CREATE INDEX IF NOT EXISTS idx_commerce_stock_outbox_pending
    ON commerce_schema.stock_outbox(status, next_attempt_at, id);

CREATE INDEX IF NOT EXISTS idx_customer_stock_outbox_pending
    ON customer_schema.stock_outbox(status, next_attempt_at, id);

DO $$
DECLARE
    target RECORD;
    index_definition TEXT;
BEGIN
    FOR target IN
        SELECT * FROM (VALUES
            ('commerce_schema', 'stock_outbox', 'idx_commerce_stock_outbox_pending'),
            ('customer_schema', 'stock_outbox', 'idx_customer_stock_outbox_pending')
        ) AS expected_indexes(schema_name, table_name, index_name)
    LOOP
        SELECT pg_get_indexdef(i.indexrelid)
        INTO index_definition
        FROM pg_index i
        JOIN pg_class index_class ON index_class.oid = i.indexrelid
        JOIN pg_namespace ns ON ns.oid = index_class.relnamespace
        WHERE ns.nspname = target.schema_name
          AND index_class.relname = target.index_name
          AND i.indrelid = format('%I.%I', target.schema_name, target.table_name)::regclass;

        IF NOT FOUND OR index_definition NOT ILIKE '%USING btree (status, next_attempt_at, id)%' THEN
            RAISE EXCEPTION 'Polling index %.% is missing or incompatible',
                target.schema_name, target.index_name;
        END IF;
    END LOOP;
END
$$;

COMMIT;
